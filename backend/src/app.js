// Flights to a city — real Amadeus when credentials present, mock fallback otherwise
app.get('/api/cities/:iata/flights', async (req, res) => {
  const iata = req.params.iata.toUpperCase();
  const airport = airports.find((a) => a.iata === iata);
  if (!airport) return res.status(404).json({ error: 'City not found' });

  const defaultDate = new Date(Date.now() + 30 * 86_400_000).toISOString().slice(0, 10);
  const departureDate = req.query.departureDate || defaultDate;
  const adults = parseInt(req.query.adults) || 1;
  const origin = req.query.origin || 'IST';

  const base = { iata, city: airport.city, from: origin, departureDate };

  // Reuse the curated mock for this IATA if it matches one of the 10 destinations
  const curated = destinations.find((d) => d.iata === iata);

  // Priority: Duffel (real-time) → Travelpayouts (cached) → mock
  const duffel = await fetchDuffelFlights(origin, iata, departureDate, adults);
  if (duffel) return res.json({ ...base, ...duffel });

  const tp = await fetchLiveFlights(origin, iata, departureDate);
  if (tp) return res.json({ ...base, ...tp });

  if (amadeus) {
    const cacheKey = `flights:${origin}:${iata}:${departureDate}:${adults}`;
    const cached = getCached(cacheKey);
    if (cached) return res.json({ ...base, source: 'live-cached', flights: cached });
    try {
      const response = await amadeus.shopping.flightOffersSearch.get({
        originLocationCode: origin, destinationLocationCode: iata,
        departureDate, adults: String(adults), max: '10', currencyCode: 'USD'
      });
      const carriers = response.result?.dictionaries?.carriers ?? {};
      const flights = response.data.map((offer) => mapOffer(offer, carriers));
      setCache(cacheKey, flights);
      return res.json({ ...base, source: 'live', flights });
    } catch (err) {
      console.error('Amadeus flight error:', err.description ?? err.message);
    }
  }

  const mockFlights = curated
    ? buildFlights(curated)
    : buildGenericFlights(iata, airport.city, origin);
  res.json({ ...base, source: 'mock', flights: mockFlights });
});

// Hotels in a city — Travelpayouts/Hotellook → Amadeus → mock
app.get('/api/cities/:iata/hotels', async (req, res) => {
  const iata = req.params.iata.toUpperCase();
  const airport = airports.find((a) => a.iata === iata);
  if (!airport) return res.status(404).json({ error: 'City not found' });

  const defaultCheckIn  = new Date(Date.now() + 30 * 86_400_000).toISOString().slice(0, 10);
  const defaultCheckOut = new Date(Date.now() + 33 * 86_400_000).toISOString().slice(0, 10);
  const checkIn  = req.query.checkIn  || defaultCheckIn;
  const checkOut = req.query.checkOut || defaultCheckOut;
  const adults   = parseInt(req.query.adults) || 1;

  const base = { iata, city: airport.city, checkIn, checkOut, adults };
  const curated = destinations.find((d) => d.iata === iata);

  // Priority: RapidAPI Booking.com → Travelpayouts → mock
  const rapidHotels = await fetchLiveHotelsRapidAPI(airport.city, checkIn, checkOut, adults);
  if (rapidHotels) return res.json({ ...base, ...rapidHotels });

  const tp = await fetchLiveHotelsTP(airport.city, checkIn, checkOut, adults);
  if (tp) return res.json({ ...base, ...tp });

  // Amadeus fallback
  if (amadeus) {
    try {
      const dest = curated || { code: airport.country, iata };
      const hotels = await fetchLiveHotels(dest, checkIn, checkOut, adults);
      if (hotels.length) return res.json({ ...base, source: 'live', hotels });
    } catch (err) {
      console.error('Amadeus hotel error:', err.description ?? err.message);
    }
  }

  const mockHotels = curated ? buildHotels(curated) : buildGenericHotels(iata, airport.city);
  res.json({ ...base, source: 'mock', hotels: mockHotels });
});

