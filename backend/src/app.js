// ── Password hashing (Node built-in scrypt — no external dependency) ──────────
function hashPassword(password) {
  const salt = randomBytes(16).toString('hex');
  const hash = scryptSync(password, salt, 64).toString('hex');
  return { salt, hash };
}

function verifyPassword(password, salt, hash) {
  if (!salt || !hash) return false;
  const derived = scryptSync(password, salt, 64);
  const stored = Buffer.from(hash, 'hex');
  return derived.length === stored.length && timingSafeEqual(derived, stored);
}

function publicUser(u) {
  const { salt, hash, password, ...rest } = u;
  return rest;
}

// Seed the demo account once per warm instance (idempotent, never overwrites).
let seedPromise;
function ensureSeed() {
  if (!seedPromise) {
    seedPromise = (async () => {
      const users = await store.readDoc('users', {});
      if (!users[DEMO_EMAIL]) {
        const { salt, hash } = hashPassword('explorer');
        users[DEMO_EMAIL] = {
          id: 'u-demo', name: 'Sıla Kırılmaz', email: DEMO_EMAIL,
          salt, hash, homeAirport: 'Istanbul — IST', currency: 'USD ($)', language: 'English'
        };
        await store.writeDoc('users', users);
        const saved = await store.readDoc('saved', {});
        if (!saved['u-demo']) {
          saved['u-demo'] = ['JP', 'FR', 'GR'];
          await store.writeDoc('saved', saved);
        }
      }
    })().catch((err) => {
      seedPromise = null; // allow a retry on the next request if seeding failed
      throw err;
    });
  }
  return seedPromise;
}

function auth(req, res, next) {
  const token = (req.headers.authorization || '').replace('Bearer ', '');
  if (!token) return res.status(401).json({ error: 'Missing token' });
  try { req.userId = jwt.verify(token, JWT_SECRET).sub; next(); }
  catch { res.status(401).json({ error: 'Invalid token' }); }
}

