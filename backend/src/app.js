const AIRLINES = ['Turkish Airlines', 'Pegasus', 'Lufthansa', 'Emirates', 'Qatar Airways'];
const STOPS = ['Direct', 'Direct', '1 Stop', 'Direct'];
const DEP_TIMES = ['09:40', '11:15', '14:50', '08:20'];
const ARR_TIMES = ['13:00', '16:20', '20:35', '12:35'];
const DURATIONS = ['3h 20m', '5h 05m', '6h 45m', '4h 15m'];

function buildGenericFlights(iata, city, origin) {
  const base = 400 + (iata.charCodeAt(0) + iata.charCodeAt(1) + iata.charCodeAt(2)) % 600;
  return DEP_TIMES.map((dep, i) => ({
    id: `${iata}-${i}`,
    airline: AIRLINES[i % AIRLINES.length],
    from: origin,
    to: iata,
    depart: dep,
    arrive: ARR_TIMES[i],
    duration: DURATIONS[i],
    stops: STOPS[i],
    price: base + i * 20 - (STOPS[i].includes('Stop') ? 40 : 0),
    deepLink: `https://www.skyscanner.net/transport/flights/${origin.toLowerCase()}/${iata.toLowerCase()}/`
  })).sort((a, b) => a.price - b.price);
}

const HOTEL_CHAINS = ['Marriott', 'Hilton', 'Hyatt', 'Radisson', 'Accor'];
const HOTEL_TYPES  = ['City Hotel', 'Resort', 'Boutique Hotel', 'Luxury Hotel', 'Budget Hotel'];

function buildGenericHotels(iata, city) {
  const base = 60 + (iata.charCodeAt(0) + iata.charCodeAt(2)) % 80;
  return HOTEL_CHAINS.map((chain, i) => ({
    id: `${iata}-hotel-${i}`,
    name: `${chain} ${city}`,
    chain,
    type: HOTEL_TYPES[i],
    stars: [5, 4, 4, 3, 3][i],
    rating: parseFloat((4.5 - i * 0.1).toFixed(1)),
    reviews: 200 + i * 150,
    pricePerNight: base + i * 15,
    currency: 'USD',
    amenities: ['WiFi', ...(i < 3 ? ['Pool'] : []), 'Restaurant'],
    address: `${city} City Centre`,
    deepLink: `https://www.booking.com/searchresults.html?ss=${encodeURIComponent(city)}`
  }));
}

const CAR_AGENCIES  = ['Hertz', 'Avis', 'Europcar', 'Sixt', 'Budget'];
const CAR_MODELS    = ['Toyota Yaris or similar', 'VW Golf or similar', 'Toyota RAV4 or similar', 'Mercedes C-Class or similar', 'Ford Galaxy or similar'];
const CAR_CATS      = ['Economy', 'Compact', 'SUV', 'Premium', 'Minivan'];

function buildGenericCars(iata, city) {
  const base = 25 + (iata.charCodeAt(1)) % 20;
  return CAR_AGENCIES.map((agency, i) => ({
    id: `${iata}-car-${i}`,
    agency,
    category: CAR_CATS[i],
    model: CAR_MODELS[i],
    transmission: i === 0 ? 'Manual' : 'Automatic',
    seats: [4, 5, 5, 5, 7][i],
    pricePerDay: base + i * 8,
    currency: 'USD',
    features: ['AC', ...(i > 1 ? ['GPS'] : [])],
    pickupLocation: `${iata} Airport`,
    deepLink: `https://www.rentalcars.com/en/airport/${iata.toLowerCase()}/`
  }));
}

