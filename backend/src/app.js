app.post('/api/auth/register', async (req, res) => {
  const { name, email, password } = req.body || {};
  if (!name || !email || !password) return res.status(400).json({ error: 'Missing fields' });
  await ensureSeed();
  const users = await store.readDoc('users', {});
  if (users[email]) return res.status(409).json({ error: 'Email already registered' });
  const { salt, hash } = hashPassword(password);
  const user = { id: `u-${Date.now()}`, name, email, salt, hash, homeAirport: 'Istanbul — IST', currency: 'USD ($)', language: 'English' };
  users[email] = user;
  await store.writeDoc('users', users);
  const token = jwt.sign({ sub: user.id }, JWT_SECRET, { expiresIn: '7d' });
  res.json({ token, user: publicUser(user) });
});

app.post('/api/auth/login', async (req, res) => {
  const { email, password } = req.body || {};
  await ensureSeed();
  const users = await store.readDoc('users', {});
  const user = users[email];
  if (!user || !verifyPassword(password, user.salt, user.hash)) {
    return res.status(401).json({ error: 'Invalid credentials' });
  }
  const token = jwt.sign({ sub: user.id }, JWT_SECRET, { expiresIn: '7d' });
  res.json({ token, user: publicUser(user) });
});

app.get('/api/auth/me', auth, async (req, res) => {
  const users = await store.readDoc('users', {});
  const user = Object.values(users).find((u) => u.id === req.userId);
  if (!user) return res.status(404).json({ error: 'Not found' });
  res.json(publicUser(user));
});

app.put('/api/auth/me', auth, async (req, res) => {
  const users = await store.readDoc('users', {});
  const entry = Object.entries(users).find(([, u]) => u.id === req.userId);
  if (!entry) return res.status(404).json({ error: 'Not found' });
  const [email, user] = entry;
  const { name, homeAirport, currency, language } = req.body || {};
  if (name) user.name = name;
  if (homeAirport) user.homeAirport = homeAirport;
  if (currency) user.currency = currency;
  if (language) user.language = language;
  users[email] = user;
  await store.writeDoc('users', users);
  res.json(publicUser(user));
});

